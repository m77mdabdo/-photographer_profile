/**
 * ═══════════════════════════════════════════════════════════════════════════
 * TASK 36b C — THE DEMO CONTENT, IN ARABIC.
 *
 * The 28 records the demo seeders create were seeded in English only, so /ar
 * served an Arabic interface wrapped around English content: every project
 * title, every excerpt, every standfirst and every article body arrived
 * through the fallback. The dashboard counted it — 28 records waiting — and
 * the render scan could not see it, because that scan translates everything
 * before it looks (see ArabicRenderTest).
 *
 * WHY ONE FILE AND NOT FOUR. The English for a record lives beside the record
 * in its own seeder, which is right: that is where somebody adds a project.
 * The Arabic is a different kind of object — one editorial pass over the whole
 * site, written to be read as Arabic rather than as a column of translations —
 * and a translator reviewing it needs to read it in one place, in order, the
 * way a reader meets it. Splitting it across four seeders would make that
 * impossible and would bury it among slugs and media ids.
 *
 * HOW IT WRITES. fillMissingTranslations() on the shared trait: only rows the
 * seeder owns (is_demo), only attributes with nothing in Arabic yet. A deploy
 * never replaces a word the studio has written. See the trait for the one case
 * it cannot distinguish and why that trade was taken.
 *
 * ───────────────────────────────────────────────────────────────────────────
 * THE REGISTER. The English here is a working photographer's prose: short
 * declaratives, no adjectives doing work a noun could do, the occasional dry
 * aside. Arabic that reads as translation does the opposite — it reaches for
 * فخامة and ends up sounding like a brochure. So this is فصحى معاصرة of the
 * kind a serious Arabic design magazine prints: verbal sentences where the
 * English uses verbs, nominal ones where it states a fact, and no ornament
 * that the English does not have.
 *
 * Where a literal rendering would be false, the sentence is rewritten to say
 * the same thing the way Arabic says it. "What they did with the silence is
 * the series" is not a sentence Arabic builds that way; "ما فعله كلٌّ منهم
 * بالصمت هو ما تبقّى من الجلسة" is.
 * ───────────────────────────────────────────────────────────────────────────
 *
 * C3 — THE INVENTED PUBLICATION NAMES ARE LEFT IN LATIN, AND ISOLATED.
 *
 * The clients are invented mastheads and institutions: Nord & Vale, Meridian
 * Press, Aperture Quarterly, The Gentlewoman, Studio Halcyon, Harbour Trust,
 * Civic Archive. They stay in Latin script, for the reason a real Arabic
 * design magazine keeps them: a masthead is closer to a logo than to a word,
 * and a client credit that transliterates the client has changed the client's
 * name. An Arabic studio's client list genuinely contains both kinds, and the
 * ones that stay Latin stay Latin.
 *
 * "Self-initiated" is NOT one of them. It is not a name, it is the absence of
 * a client, so it becomes مشروع ذاتي.
 *
 * AND THE LATIN NAMES ARE WRAPPED IN A BIDI ISOLATE, which is the part that
 * is easy to get wrong. Once "The Gentlewoman" is stored as the ARABIC value
 * it is no longer a fallback — Fallback::from() returns null and the renderer
 * annotates nothing — so the element would carry Latin text inside an RTL
 * paragraph with nothing to declare it, which is the exact bug Part A fixes
 * arriving by a different road. U+2068 … U+2069 travels with the characters,
 * so it is correct in text, in an attribute and in JSON-LD alike, and
 * FallbackAnnotationTest treats an isolated run as declared.
 * ═══════════════════════════════════════════════════════════════════════════
 */
class DemoArabicSeeder extends Seeder

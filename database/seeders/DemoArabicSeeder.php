    /*
     * NO SLUGS HERE, DELIBERATELY. The first version set an Arabic slug per
     * record and every one was refused: a slug always has a value in every
     * locale (Translatable::setTranslations enforces it, because the
     * generated column is NOT NULL), so none of them was ever "missing".
     *
     * Leaving them refused would have been fine and misleading. Changing an
     * Arabic slug changes a live URL, which is a decision for the owner with
     * the redirect machinery behind it — not a side effect of a translation
     * pass. /ar/work/salt-line stays what it is.
     */

    /** A foreign proper noun inside Arabic prose. See C3 above. */
    private function latin(string $name): string
    {
        return Fallback::FSI.$name.Fallback::PDI;
    }

    public function run(): void
    {
        $filled = 0;

        $filled += $this->projects();
        $filled += $this->services();
        $filled += $this->articles();
        $filled += $this->pages();
        $filled += $this->taxonomy();
        $filled += $this->clients();
        $filled += $this->projectClients();

        $this->command?->info("Arabic: {$filled} attributes filled.");
    }

    /**
     * Find a demo record by its English slug and fill its Arabic.
     *
     * @param  class-string<Model>  $model
     * @param  array<string, string>  $values
     */
    private function fill(string $model, string $slug, array $values, bool $requireOwnership = true): int
    {
        /** @var Model|null $record */
        $record = $model::query()->whereRaw('JSON_UNQUOTE(JSON_EXTRACT(slug, "$.en")) = ?', [$slug])->first();

        if ($record === null) {
            return 0;
        }

        return $this->fillMissingTranslations($record, 'ar', $values, $requireOwnership);
    }

    /**
     * The same thing for a record with no slug.
     *
     * `clients` is one translatable column — the name — so there is nothing
     * else to find it by. Matched on the English name, which is unique in
     * the library and is what an owner would recognise in this file.
     *
     * @param  class-string<Model>  $model
     * @param  array<string, string>  $values
     */
    private function fillByName(string $model, string $name, array $values, bool $requireOwnership = true): int
    {
        /** @var Model|null $record */
        $record = $model::query()->whereRaw('JSON_UNQUOTE(JSON_EXTRACT(name, "$.en")) = ?', [$name])->first();

        if ($record === null) {
            return 0;
        }

        return $this->fillMissingTranslations($record, 'ar', $values, $requireOwnership);
    }


#!/usr/bin/env python3
"""
Generate app/Support/WordmarkMetrics.php from the shipped Arabic display face.

Task 38 Part A, second pass. The Arabic hero cuts the wordmark at the space
between its words, so the server has to know how wide each word will set —
before any script runs, so the plate is never moved after first paint.

A character count cannot say that: "أنس" sets at 0.646em per character and
"فريد" at 0.480, measured in the browser. What can is the font itself. Arabic
joining is rule-based, so each letter's positional form (isolated, initial,
medial, final) follows from its neighbours, and the font's GSUB init / medi /
fina substitutions name the glyph for each form. Summing those glyphs'
advances reproduced the browser to three decimals: 1.939em against 1.938
measured for "أنس", 1.922 against 1.920 for "فريد". Kerning is not applied;
the difference it would make is inside --split-clear.

Each advance is the WIDER of the two display weights the registers use (800
on ink, 860 on paper), so one table serves both themes as an upper bound.

Run after changing public/fonts/rubik-arabic.woff2:
    python3 bin/wordmark-metrics.py
"""
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

FONT = 'public/fonts/rubik-arabic.woff2'
OUT = 'app/Support/WordmarkMetrics.php'
WEIGHTS = (800, 860)
FORMS = ('isol', 'init', 'medi', 'fina')


def read(weight):
    g = instantiateVariableFont(TTFont(FONT), {'wght': weight})
    cmap, hmtx, upm = g.getBestCmap(), g['hmtx'], g['head'].unitsPerEm
    subs = {f: {} for f in FORMS[1:]}
    gsub = g['GSUB'].table
    for record in gsub.FeatureList.FeatureRecord:
        if record.FeatureTag in subs:
            for index in record.Feature.LookupListIndex:
                lookup = gsub.LookupList.Lookup[index]
                for table in lookup.SubTable:
                    if lookup.LookupType == 7:
                        table = table.ExtSubTable
                    if hasattr(table, 'mapping'):
                        subs[record.FeatureTag].update(table.mapping)
    table = {}
    for code, glyph in cmap.items():
        if not (0x0600 <= code <= 0x06FF):
            continue
        row = [hmtx[glyph][0] / upm]
        for form in FORMS[1:]:
            row.append(hmtx[subs[form].get(glyph, glyph)][0] / upm)
        table[code] = row
    return table


tables = [read(w) for w in WEIGHTS]
merged = {c: [max(t[c][i] for t in tables) for i in range(4)] for c in tables[0]}

lines = [f"        0x{c:04X} => [{', '.join(f'{v:.3f}' for v in row)}]," for c, row in sorted(merged.items())]

php = """<?php

declare(strict_types=1);

namespace App\\Support;

/**
 * GENERATED by bin/wordmark-metrics.py from public/fonts/rubik-arabic.woff2.
 * Do not edit by hand; re-run the script after changing the font.
 *
 * How wide an Arabic word sets in the display face, in em, so the hero can
 * place its plate over the space between two words without measuring in the
 * browser (Task 38 Part A, second pass). See the script for the method and
 * the measurement that validated it.
 */
final class WordmarkMetrics
{
    /** em advance per codepoint: [isolated, initial, medial, final] */
    private const ADVANCE = [
%s
    ];

    /**
     * Letters that join only to the letter BEFORE them (Unicode joining type
     * R) or to nothing (U): after one of these the next letter starts afresh.
     */
    private const RIGHT_JOINING = 'اأإآٱدذرزوؤةى';

    private const NON_JOINING = 'ء';

    /** A character the table does not know is assumed this wide — wider than any letter in it. */
    public const UNKNOWN = 0.75;

    public static function width(string $word): float
    {
        // Vowel marks and other zero-width characters are transparent to
        // joining: a letter either side of a shadda still joins across it.
        // They add nothing to the width, so they are dropped first.
        $chars = array_values(array_filter(
            mb_str_split($word),
            static fn (string $c): bool => (self::ADVANCE[mb_ord($c)][0] ?? 1.0) > 0.0,
        ));
        $total = 0.0;

        foreach ($chars as $i => $char) {
            $code = mb_ord($char);

            if (! isset(self::ADVANCE[$code])) {
                // Harakat and other zero-width marks are in the table at 0;
                // anything else unknown is assumed wide rather than narrow.
                $total += self::UNKNOWN;

                continue;
            }

            $joinsBefore = $i > 0 && self::joinsForward($chars[$i - 1]) && self::joins($char);
            $joinsAfter = $i < count($chars) - 1 && self::joinsForward($char) && self::joins($chars[$i + 1]);

            $form = match (true) {
                $joinsBefore && $joinsAfter => 2,
                $joinsBefore => 3,
                $joinsAfter => 1,
                default => 0,
            };

            $total += self::ADVANCE[$code][$form];
        }

        return $total;
    }

    private static function joins(string $char): bool
    {
        return isset(self::ADVANCE[mb_ord($char)]) && ! str_contains(self::NON_JOINING, $char);
    }

    private static function joinsForward(string $char): bool
    {
        return self::joins($char) && ! str_contains(self::RIGHT_JOINING, $char);
    }
}
""" % '\n'.join(lines)

open(OUT, 'w').write(php)
print(f'{OUT}: {len(merged)} codepoints')

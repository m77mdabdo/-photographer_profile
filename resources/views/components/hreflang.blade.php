@php
    use App\Support\Locale;

    /*
     * THE ALTERNATES ARE BUILT FROM THE PATH, NOT FROM A ROUTE NAME.
     *
     * Every public page has a direct equivalent in the other locale at the
     * same path with a different prefix, so the path is all this needs. The
     * alternative — reconstructing a route name and its bound model per page —
     * would mean every controller passing its own alternates, and the one
     * controller that forgot would emit a page with no reciprocal link, which
     * is the single failure hreflang is least forgiving of.
     *
     * Reciprocity is the rule that makes hreflang work at all: Google ignores
     * an annotation that the named page does not return the compliment. Because
     * both sides of every pair are generated by this same component from the
     * same path, they cannot disagree.
     */
    $path = request()->getPathInfo();

    /*
     * SLUG-AWARE. Locale::alternates() swaps only the prefix, which emits an
     * annotation pointing at an address that 301s once slugs differ per
     * locale — see LocaleAlternates for why that is worse than it sounds.
     */
    $alternates = \App\Support\LocaleAlternates::forRequest(request());

    /*
     * x-default is the address for a visitor whose language we do not serve.
     * It is the unprefixed English page — the same URL as the `en` alternate,
     * deliberately. x-default does not mean "English"; it means "the page to
     * use when none of the others match", and on this site that is the
     * non-negotiated root of the default locale. Pointing it at a negotiating
     * address would be the classic mistake, since the root here only
     * negotiates for a visitor who already has a preference.
     */
    $default = $alternates[Locale::DEFAULT];
@endphp
@foreach ($alternates as $code => $url)
<link rel="alternate" hreflang="{{ Locale::html($code) }}" href="{{ $url }}">
@endforeach
<link rel="alternate" hreflang="x-default" href="{{ $default }}">
